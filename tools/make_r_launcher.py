"""Wrap an R script in a Python launcher for Kaggle (which no longer runs R kernels; R is installed in the Python image).

Usage: python3 tools/make_r_launcher.py kaggle/hn-12-revsurvey/hn-12-revsurvey.R
Writes <name>.py next to the R file; the launcher writes the R source to disk and runs it with Rscript.
"""
import sys
from pathlib import Path

src = Path(sys.argv[1])
code = src.read_text()
assert "'''" not in code
out = src.with_suffix(".py")
out.write_text(f'''# Generated by tools/make_r_launcher.py from {src.name}; edit the R file, not this one.
import subprocess
import sys
from pathlib import Path

R_SOURCE = r\'\'\'{code}\'\'\'
Path("{src.name}").write_text(R_SOURCE)
r = subprocess.run(["Rscript", "{src.name}"])
sys.exit(r.returncode)
''')
print("wrote", out)
